package main

import (
	"bytes"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

func TestExecutable(t *testing.T) {
	d := t.TempDir()
	bin := filepath.Join(d, "tdelta")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	if data, err := exec.Command("go", "build", "-buildvcs=false", "-mod=readonly", "-o", bin, ".").CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, data)
	}
	base, target := filepath.Join(d, "before.txt"), filepath.Join(d, "after.txt")
	patch, result := filepath.Join(d, "change.dcd"), filepath.Join(d, "result.txt")
	for path, data := range map[string]string{base: "before\r\n", target: "after\r\n🙂"} {
		if err := os.WriteFile(path, []byte(data), 0600); err != nil {
			t.Fatal(err)
		}
	}
	for _, tc := range []struct {
		args     []string
		code     int
		contains string
	}{
		{[]string{"--help"}, 0, "tdelta"},
		{[]string{"diff", base, base}, 0, ""},
		{[]string{"diff", base, target}, 1, "@@ -1 +1,2 @@"},
		{[]string{"create", base, target, "--output", patch}, 0, ""},
		{[]string{"apply", base, patch, "--output", result}, 0, ""},
		{[]string{"apply", base, "-", "--output", "-"}, 0, "after\r\n🙂"},
		{[]string{"show", base, patch}, 1, "+🙂"},
		{[]string{"apply", target, patch, "--output", "-"}, 2, "base"},
	} {
		var code int
		command := exec.Command(bin, tc.args...)
		if tc.args[0] == "apply" && tc.args[2] == "-" {
			f, err := os.Open(patch)
			if err != nil {
				t.Fatal(err)
			}
			defer f.Close()
			command.Stdin = f
		}
		var stderr bytes.Buffer
		command.Stderr = &stderr
		out, err := command.Output()
		if e, ok := err.(*exec.ExitError); ok {
			code = e.ExitCode()
		} else if err != nil {
			t.Fatal(err)
		}
		text := string(out)
		if tc.code == 2 {
			if text != "" {
				t.Fatalf("unexpected stdout: %q", text)
			}
			text = stderr.String()
		} else if stderr.Len() != 0 {
			t.Fatalf("unexpected stderr: %s", &stderr)
		}
		if code != tc.code || (tc.contains == "" && text != "") || !strings.Contains(text, tc.contains) {
			t.Fatalf("%q: code=%d text=%q; want %d, %q", tc.args, code, text, tc.code, tc.contains)
		}
	}
	for _, file := range []string{target, result} {
		f, err := os.Open(file)
		if err != nil {
			t.Fatal(err)
		}
		got, err := io.ReadAll(f)
		f.Close()
		if err != nil || string(got) != "after\r\n🙂" {
			t.Fatalf("generated bytes = %q: %v", got, err)
		}
	}
	t.Run("closed stdout", func(t *testing.T) {
		r, w, err := os.Pipe()
		if err != nil {
			t.Fatal(err)
		}
		if err := r.Close(); err != nil {
			w.Close()
			t.Fatal(err)
		}
		defer w.Close()
		var stderr bytes.Buffer
		command := exec.Command(bin, "apply", base, patch, "--output", "-")
		command.Stdout, command.Stderr = w, &stderr
		if err := command.Run(); err == nil || command.ProcessState.ExitCode() != 2 || stderr.Len() == 0 {
			t.Fatalf("closed stdout status=%v, error=%v, stderr=%q", command.ProcessState, err, &stderr)
		}
	})
}
